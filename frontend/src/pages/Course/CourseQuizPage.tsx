function formatDuration(seconds: number | null): string {
  if (!seconds) return "—";
  const m = Math.floor(seconds / 60);
  const s = seconds % 60;
  return m > 0 ? `${m}m ${s}s` : `${s}s`;
}

function formatDate(iso: string): string {
  try {
    return new Date(iso).toLocaleString();
  } catch {
    return iso;
  }
}

function getGenerationStepLabel(step: string | null | undefined) {
  switch (step) {
    case "load_inputs":
      return "Preparing quiz";
    case "retrieve_context":
      return "Retrieving module context";
    case "plan_quiz":
      return "Planning quiz";
    case "generate_quiz":
      return "Generating questions";
    case "validate_quiz":
      return "Validating questions";
    case "publish_quiz":
      return "Saving questions";
    case "start_generated_attempt":
      return "Starting quiz";
    default:
      return "Generating quiz";
  }
}

// ---------------------------------------------------------------------------
// Timer bar
// ---------------------------------------------------------------------------

function TimerBar({ totalSeconds, remainingSeconds }: { totalSeconds: number; remainingSeconds: number }) {
  const pct = Math.max(0, Math.min(100, (remainingSeconds / totalSeconds) * 100));
  const isWarning = pct < 25;
  return (
    <div className="quiz-timer-bar-wrap">
      <div
        className={`quiz-timer-bar-fill${isWarning ? " quiz-timer-bar-warning" : ""}`}
        style={{ width: `${pct}%` }}
      />
      <span className={`quiz-timer-label${isWarning ? " quiz-timer-label-warning" : ""}`}>
        {formatDuration(remainingSeconds)}
      </span>
    </div>
  );
}

