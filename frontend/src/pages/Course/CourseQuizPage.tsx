type QuizPageState = "idle" | "generating" | "active" | "result";

const GENERATION_RUN_POLL_MS = 1000;

function getGenerationRunStorageKey(courseUuid: string, moduleUuid: string) {
  return `quizGenerationRun:${courseUuid}:${moduleUuid}`;
}

function getErrorMessage(error: unknown, fallbackMessage: string) {
  return error instanceof Error && error.message.trim() ? error.message : fallbackMessage;
}

function CourseQuizPage() {
  const { moduleUuid } = useParams();
  const { course, setQuizGuard, markModuleCompleted, refreshCourse } = useOutletContext<CourseOutletContext>();
  const module = course.modules.find((m) => m.moduleUuid === moduleUuid) ?? null;
  const activeModuleUuid = module?.moduleUuid ?? null;

  const [pageState, setPageState] = useState<QuizPageState>("idle");
  const [answers, setAnswers] = useState<Record<string, string | null>>({});
  const [history, setHistory] = useState<QuizAttemptHistory | null>(null);
  const [isLoadingHistory, setIsLoadingHistory] = useState(true);
  const [session, setSession] = useState<QuizAttemptSession | null>(null);
  const [result, setResult] = useState<QuizAttemptResult | null>(null);
  const [historyResult, setHistoryResult] = useState<QuizAttemptResult | null>(null);
  const [isStarting, setIsStarting] = useState(false);
  const [toastMessage, setToastMessage] = useState<{
    title: string;
    message: string;
    variant: "success" | "error";
  } | null>(null);
  const [, setGenerationEvents] = useState<QuizGenerationProgressEvent[]>([]);
  const [currentGenerationStep, setCurrentGenerationStep] = useState<string>("Generating quiz");
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [submitError, setSubmitError] = useState<string | null>(null);
  const [historyDetailError, setHistoryDetailError] = useState<string | null>(null);
  const [historyLoadError, setHistoryLoadError] = useState<string | null>(null);
  const [loadingAttemptUuid, setLoadingAttemptUuid] = useState<string | null>(null);
  const [generationRunId, setGenerationRunId] = useState<string | null>(null);
  const [overviewReloadKey, setOverviewReloadKey] = useState(0);
  const generationRunStorageKey = module ? getGenerationRunStorageKey(course.courseUuid, module.moduleUuid) : null;
  const pageStateRef = useRef(pageState);
  // Keep latest answers in a ref so the quiz guard callback always sees current values
  const answersRef = useRef<Record<string, string | null>>({});
  useEffect(() => { answersRef.current = answers; }, [answers]);
  useEffect(() => { pageStateRef.current = pageState; }, [pageState]);

  const applyGenerationRunStatus = useCallback((run: QuizGenerationRun) => {
    setGenerationEvents(run.events);
    if (run.currentStep) {
      setCurrentGenerationStep(getGenerationStepLabel(run.currentStep));
    } else if (run.message) {
      setCurrentGenerationStep(run.message);
    }

    if (run.status === "completed") {
      if (!run.attemptStartResponse) {
        throw new Error("Quiz generation completed without a quiz session.");
      }
      if (generationRunStorageKey) window.sessionStorage.removeItem(generationRunStorageKey);
      setGenerationRunId(null);
      setSession(run.attemptStartResponse);
      setPageState("active");
      if (activeModuleUuid) {
        emitAppRefresh({ scope: "course:quiz", courseUuid: course.courseUuid, moduleUuid: activeModuleUuid });
      }
      setToastMessage({
        title: "已恢复生成的测验。",
        message: "你生成的测验会话已准备好。",
        variant: "success",
      });
      return;
    }

    if (run.status === "failed") {
      if (generationRunStorageKey) window.sessionStorage.removeItem(generationRunStorageKey);
      setGenerationRunId(null);
      setPageState("idle");
      setToastMessage({
        title: "测验生成失败。",
        message: run.error || run.message || "请重新生成测验。",
        variant: "error",
      });
    }
  }, [activeModuleUuid, course.courseUuid, generationRunStorageKey]);

  useEffect(() => {
    setPageState("idle");
    setSession(null);
    setResult(null);
    setHistoryResult(null);
    setAnswers({});
    setToastMessage(null);
    setGenerationEvents([]);
    setCurrentGenerationStep("Generating quiz");
    setSubmitError(null);
    setHistoryDetailError(null);
    setHistoryLoadError(null);
    setLoadingAttemptUuid(null);
    setGenerationRunId(null);
  }, [moduleUuid]);

  useEffect(() => {
    if (!generationRunStorageKey || !activeModuleUuid) return;
    const storedRunId = window.sessionStorage.getItem(generationRunStorageKey);
    if (storedRunId) {
      setGenerationRunId(storedRunId);
      setPageState("generating");
      setCurrentGenerationStep("Checking generated quiz status");
      return;
    }

    let cancelled = false;
    void getActiveAutoGeneratedQuizAttemptRun(course.courseUuid, activeModuleUuid)
      .then((run) => {
        if (cancelled || !run || run.status === "failed") return;
        if (run.status === "completed") {
          applyGenerationRunStatus(run);
          return;
        }
        window.sessionStorage.setItem(generationRunStorageKey, run.runId);
        setGenerationRunId(run.runId);
        setPageState("generating");
        setCurrentGenerationStep(run.currentStep ? getGenerationStepLabel(run.currentStep) : "Checking generated quiz status");
      })
      .catch(() => {
        // No active run is fine; the normal quiz overview should render.
      });

    return () => {
      cancelled = true;
    };
  }, [activeModuleUuid, applyGenerationRunStatus, course.courseUuid, generationRunStorageKey]);

  // Reset answers when returning to idle
  useEffect(() => {
    if (pageState === "idle") setAnswers({});
  }, [pageState]);

  useEffect(() => {
    if (!toastMessage) return;
    const timer = window.setTimeout(() => setToastMessage(null), 2600);
    return () => window.clearTimeout(timer);
  }, [toastMessage]);

  useEffect(() => {
    if (!activeModuleUuid || !generationRunId || pageState !== "generating") return;

    let cancelled = false;
    let timeoutId: number | null = null;

    const pollRun = async () => {
      try {
        const run = await getAutoGeneratedQuizAttemptRun(course.courseUuid, activeModuleUuid, generationRunId);
        if (cancelled) return;
        applyGenerationRunStatus(run);
        if (run.status === "queued" || run.status === "running") {
          timeoutId = window.setTimeout(pollRun, GENERATION_RUN_POLL_MS);
        }
      } catch (err) {
        if (cancelled) return;
        const activeSession = await getActiveQuizSession(course.courseUuid, activeModuleUuid).catch(() => null);
        if (cancelled) return;
        if (activeSession) {
          if (generationRunStorageKey) window.sessionStorage.removeItem(generationRunStorageKey);
          setGenerationRunId(null);
          setSession(activeSession);
          setPageState("active");
          setToastMessage({
            title: "已恢复生成的测验。",
            message: "我们已找到你的测验会话并打开本次尝试。",
            variant: "success",
          });
          return;
        }
        if (generationRunStorageKey) window.sessionStorage.removeItem(generationRunStorageKey);
        setGenerationRunId(null);
        setPageState("idle");
        setToastMessage({
          title: "无法恢复测验生成。",
          message: err instanceof Error ? err.message : "请重新生成测验。",
          variant: "error",
        });
      }
    };

    void pollRun();

    return () => {
      cancelled = true;
      if (timeoutId !== null) window.clearTimeout(timeoutId);
    };
  }, [activeModuleUuid, applyGenerationRunStatus, course.courseUuid, generationRunId, generationRunStorageKey, pageState]);

  // Register/clear quiz guard in CourseLayout
  useEffect(() => {
    if (!activeModuleUuid) return;
    if (pageState === "active" && session) {
      setQuizGuard(true, async () => {
        const payload = session.questions.map((q) => ({
          questionUuid: q.questionUuid,
          selectedOptionUuid: answersRef.current[q.questionUuid] ?? null,
        }));
        try {
          await submitQuizAttempt(course.courseUuid, activeModuleUuid, session.attemptSessionToken, payload);
        } catch { /* ignore */ }
      });
    } else {
      setQuizGuard(false);
    }
    return () => setQuizGuard(false);
  }, [activeModuleUuid, course.courseUuid, pageState, session, setQuizGuard]);

  useEffect(() => {
    if (!activeModuleUuid) return;
    setIsLoadingHistory(true);
    setHistoryLoadError(null);
    let cancelled = false;
    Promise.allSettled([
      getQuizAttemptHistory(course.courseUuid, activeModuleUuid),
      module?.hasPublishedQuiz
        ? getActiveQuizSession(course.courseUuid, activeModuleUuid)
        : Promise.resolve(null),
    ]).then(([historyResult, activeSessionResult]) => {
      if (cancelled) return;
      if (historyResult.status === "fulfilled") {
        setHistory(historyResult.value);
      } else {
        setHistory(null);
        setHistoryLoadError(getErrorMessage(historyResult.reason, "Failed to load quiz history."));
      }

      if (activeSessionResult.status === "rejected") {
        setHistoryLoadError((current) =>
          current ?? getErrorMessage(activeSessionResult.reason, "Failed to check active quiz session.")
        );
        return;
      }

      const activeSession = activeSessionResult.value;
      if (activeSession && pageStateRef.current === "idle") {
        const wasRecoveringGeneration = generationRunStorageKey
          ? window.sessionStorage.getItem(generationRunStorageKey) !== null
          : false;
        if (generationRunStorageKey) window.sessionStorage.removeItem(generationRunStorageKey);
        setGenerationRunId(null);
        setSession(activeSession);
        setPageState("active");
        if (wasRecoveringGeneration) {
          setToastMessage({
            title: "已恢复生成的测验。",
            message: "我们已找到你的测验会话并打开本次尝试。",
            variant: "success",
          });
        }
      }
    }).finally(() => {
      if (!cancelled) {
        setIsLoadingHistory(false);
      }
    });
    return () => {
      cancelled = true;
    };
  }, [activeModuleUuid, course.courseUuid, generationRunStorageKey, module?.hasPublishedQuiz, overviewReloadKey]);

  if (!module) {
    return <Navigate to={`/course/${course.courseUuid}`} replace />;
  }

  const handleStart = async () => {
    setIsStarting(true);
    setToastMessage(null);
    try {
      const s = await startQuizAttempt(course.courseUuid, module.moduleUuid);
      setSession(s);
      setPageState("active");
      emitAppRefresh({ scope: "course:quiz", courseUuid: course.courseUuid, moduleUuid: module.moduleUuid });
    } catch (err) {
      setToastMessage({
        title: "无法开始测验。",
        message: err instanceof Error ? err.message : "Failed to start quiz.",
        variant: "error",
      });
    } finally {
      setIsStarting(false);
    }
  };

  const handleGenerate = async () => {
    setPageState("generating");
    setToastMessage(null);
    setGenerationEvents([]);
    setCurrentGenerationStep("Queued quiz generation");
    try {
      const run = await createAutoGeneratedQuizAttemptRun(course.courseUuid, module.moduleUuid);
      if (!run.runId) {
        throw new Error("Quiz generation did not return a run id.");
      }
      if (generationRunStorageKey) window.sessionStorage.setItem(generationRunStorageKey, run.runId);
      setGenerationRunId(run.runId);
    } catch (err) {
      if (generationRunStorageKey) window.sessionStorage.removeItem(generationRunStorageKey);
      setGenerationRunId(null);
      setToastMessage({
        title: "无法生成测验。",
        message: err instanceof Error ? err.message : "Failed to generate quiz.",
        variant: "error",
      });
      setPageState("idle");
    } finally {
      setGenerationEvents([]);
    }
  };

  const handleSubmit = async (
    payload: { questionUuid: string; selectedOptionUuid: string | null }[],
    options?: { timedOut?: boolean }
  ) => {
    if (!session) return;
    setIsSubmitting(true);
    setSubmitError(null);
    try {
      const r = await submitQuizAttempt(
        course.courseUuid,
        module.moduleUuid,
        session.attemptSessionToken,
        payload,
        options
      );
      if (generationRunStorageKey) window.sessionStorage.removeItem(generationRunStorageKey);
      setGenerationRunId(null);
      setResult(r);
      if (r.moduleCompleted) {
        markModuleCompleted(module.moduleUuid);
        emitAppRefresh({ scope: "course:progress", courseUuid: course.courseUuid, moduleUuid: module.moduleUuid });
      }
      setPageState("result");
      const h = await getQuizAttemptHistory(course.courseUuid, module.moduleUuid);
      setHistory(h);
      await refreshCourse();
      emitAppRefresh({ scope: "course:quiz", courseUuid: course.courseUuid, moduleUuid: module.moduleUuid });
    } catch (err) {
      setSubmitError(err instanceof Error ? err.message : "Failed to submit quiz.");
    } finally {
      setIsSubmitting(false);
    }
  };

  const handleRetry = () => {
    setSession(null);
    setResult(null);
    setHistoryResult(null);
    setGenerationEvents([]);
    setCurrentGenerationStep("Generating quiz");
    if (generationRunStorageKey) window.sessionStorage.removeItem(generationRunStorageKey);
    setGenerationRunId(null);
    setSubmitError(null);
    setHistoryDetailError(null);
    setPageState("idle");
  };

  const handleViewAttempt = async (quizAttemptUuid: string) => {
    setHistoryDetailError(null);
    setLoadingAttemptUuid(quizAttemptUuid);
    try {
      const detail = await getQuizAttemptDetail(course.courseUuid, module.moduleUuid, quizAttemptUuid);
      setHistoryResult(detail);
    } catch (err) {
      setHistoryDetailError(err instanceof Error ? err.message : "Failed to load quiz attempt detail.");
    } finally {
      setLoadingAttemptUuid(null);
    }
  };

  return (
    <>
      {toastMessage && (
        <div
          className={`course-management-toast${
            toastMessage.variant === "error" ? " course-management-toast-error" : " course-management-toast-success"
          }`}
          role={toastMessage.variant === "error" ? "alert" : "status"}
          aria-live={toastMessage.variant === "error" ? "assertive" : "polite"}
        >
          <strong>{toastMessage.title}</strong>
          <span>{toastMessage.message}</span>
        </div>
      )}
      {pageState === "active" && session ? (
        <ActiveQuiz
          key={session.attemptSessionToken}
          session={session}
          answers={answers}
          onAnswerChange={setAnswers}
          onSubmit={handleSubmit}
          isSubmitting={isSubmitting}
          submitError={submitError}
        />
      ) : pageState === "generating" ? (
        <GeneratingView currentStepLabel={currentGenerationStep} />
      ) : pageState === "result" && result ? (
        <ResultView result={result} onRetry={handleRetry} />
      ) : historyResult ? (
        <ResultView result={historyResult} onRetry={handleRetry} onBack={() => setHistoryResult(null)} />
      ) : (
        <section className="course-detail-page">
          <div className="course-module-hero">
            <span className="course-surface-badge">测验</span>
            <h1>{history?.title ?? module.title}</h1>
            {history?.timeLimitSeconds ? (
              <p>时间限制： {formatDuration(history.timeLimitSeconds)}· 检查你对本模块的掌握情况。</p>
            ) : (
              <p>无时间限制 · 检查你对本模块的掌握情况。</p>
            )}
          </div>

          <div className="quiz-overview-body">
            <div className="quiz-overview-start-row">
              {history?.passedOnce && (
                <span className="quiz-passed-badge quiz-passed-badge-lg">已通过</span>
              )}
              <button
                type="button"
                className="course-primary-link"
                onClick={() => void handleStart()}
                disabled={isStarting}
              >
                {isStarting ? "启动中…" : history?.attempts && history.attempts.length > 0 ? "重试" : "开始测验"}
              </button>
            </div>

            {historyLoadError && (
              <div className="course-management-inline-alert" style={{ marginBottom: "1rem" }}>
                <strong>无法加载测验历史。</strong>
                <span>{historyLoadError}</span>
                <button
                  type="button"
                  className="course-secondary-link"
                  onClick={() => setOverviewReloadKey((value) => value + 1)}
                  disabled={isLoadingHistory}
                >
                  {isLoadingHistory ? "Retrying..." : "重试"}
                </button>
              </div>
            )}

            <div className="quiz-overview-generate-row">
              <button
                type="button"
                className="course-secondary-link quiz-generate-btn"
                onClick={() => void handleGenerate()}
                disabled={isStarting}
              >生成测验
              </button>
            </div>

            {historyDetailError && (
              <div className="course-management-inline-alert" style={{ marginBottom: "1rem" }}>
                <strong>无法加载尝试详情。</strong>
                <span>{historyDetailError}</span>
              </div>
            )}

            {!isLoadingHistory && history && (
              <HistoryTable
                history={history}
                onViewAttempt={handleViewAttempt}
                loadingAttemptUuid={loadingAttemptUuid}
              />
            )}
          </div>
        </section>
      )}

    </>
  );
}

export default CourseQuizPage;
